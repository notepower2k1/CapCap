RUNTIME_VERSION = "v0.9.3"
MODEL_REVISION = "874fcb41ececda20bcbc0782d6b4ea7f7d069ea8"
MODEL_FILE = "omnivoice-q8_0.gguf"
MODEL_SIZE = 1350296096
MODEL_SHA256 = "0e5a721edd1b08d9067ef66f40ded609a6b14f5a8445c703f9869736cabd350a"
MODEL_URL = f"https://huggingface.co/audio-cpp/audio.cpp-gguf/resolve/{MODEL_REVISION}/OmniVoice-GGUF/{MODEL_FILE}"
CUDA_LIBRARIES = ("cudart64_12.dll", "cublas64_12.dll", "cublasLt64_12.dll", "cufft64_11.dll")
INFERENCE_PRESETS = (
    ("Quality (32 steps)", 32, "Default quality. Recommended for the final voice track."),
    ("Medium (24 steps)", 24, "Balances generation time and voice quality."),
    ("Fast (16 steps)", 16, "Faster generation; pronunciation and voice similarity may decrease."),
    ("Very fast (8 steps)", 8, "Best for quick previews. Speech clarity and voice similarity may decrease noticeably."),
)


def inference_steps(value=None):
    try:
        steps = int(os.getenv("CAPCAP_OMNIVOICE_STEPS", "32") if value is None else value)
    except (ValueError, TypeError):
        return 32
    return steps if steps in {32, 24, 16, 8} else 32


def model_path():
    return Path(os.getenv("CAPCAP_OMNIVOICE_MODEL") or models_path("omnivoice", MODEL_FILE))


def runtime_path(backend="cpu"):
    override = os.getenv("CAPCAP_AUDIOCPP_SERVER", "").strip()
    if override:
        return Path(override)
    return Path(bin_path("audio_cpp", backend, "audiocpp_server.exe"))


def ready():
    model = model_path()
    if not model.is_file():
        return False
    with model.open("rb") as handle:
        if handle.read(4) != b"GGUF":
            return False
    backend = selected_backend()
    return runtime_path(backend).is_file() and (backend != "cuda" or cuda_library_dir() is not None)


def selected_backend():
    """Honor CPU mode; GPU mode prefers CUDA and never silently uses CPU."""
    if os.getenv("CAPCAP_DEVICE", "cuda").strip().lower() == "cpu":
        return "cpu"
    if runtime_path("cuda").is_file() and cuda_library_dir():
        return "cuda"
    if runtime_path("vulkan").is_file():
        return "vulkan"
    return "cuda"  # Missing GPU runtime is an actionable error, not CPU fallback.


def cuda_library_dir(runtime_directory=None):
    """Resolve a complete CUDA 12 set in Windows executable/PATH search order."""
    candidates = [Path(runtime_directory) if runtime_directory else runtime_path("cuda").parent,
                  Path(bin_path("cuda12_fw")), Path(bin_path("cuda12_fw_new"))]
    for directory in candidates:
        try:
            if all((directory/name).is_file() and (directory/name).stat().st_size > 0 for name in CUDA_LIBRARIES):
                return directory.resolve()
        except OSError:
            continue
    return None


def _voices_dir():
    return Path(join_root("models", "omnivoice", "voices"))


def _vieneu_reference_voices():
    """Expose saved audio/transcript pairs; never load VieNeu or reuse its embeddings."""
    from vieneu_tts import list_vieneu_cloned_voices
    result = []
    for source in list_vieneu_cloned_voices():
        audio = str(source.get("ref_audio") or "").strip()
        text = str(source.get("ref_text") or "").strip()
        source_id = str(source.get("id") or "")
        if not source_id.startswith("vieneu_clone:") or not text or not audio or not Path(audio).is_file():
            continue
        voice_id = "omnivoice:vieneu:" + source_id.split(":", 1)[1]
        result.append({"id": voice_id, "provider": "omnivoice", "provider_voice": voice_id.split(":", 1)[1],
            "name": str(source.get("name") or source_id) + " (VieNeu)", "language": "multilingual",
            "gender": source.get("gender", "any"), "enabled": True, "type": "cloned",
            "ref_audio": str(Path(audio).resolve()), "ref_text": text, "reference_source": "vieneu",
            "source_voice_id": source_id, "description": "Uses the reference audio and transcript saved for VieNeu. Speech is generated by OmniVoice."})
    return result


def list_voices():
    result = []
    root = _voices_dir()
    if root.is_dir():
        for path in sorted(root.glob("*.json")):
            try:
                data = json.loads(path.read_text(encoding="utf-8"))
                audio = (root/data["audio_file"]).resolve()
                if not audio.is_relative_to(root.resolve()) or not audio.is_file() or not str(data.get("ref_text") or "").strip():
                    continue
                result.append({"id": "omnivoice:"+path.stem, "provider": "omnivoice", "provider_voice": path.stem,
                    "name": data["name"], "language": "multilingual", "gender": data.get("gender", "any"),
                    "enabled": True, "type": "cloned", "ref_audio": str(audio), "ref_text": data["ref_text"],
                    "description": data.get("description", "")})
            except (OSError, ValueError, KeyError, TypeError):
                continue
    result.extend(_vieneu_reference_voices())
    return result


def _convert_reference(audio_path, target):
    subprocess.run([bin_path("ffmpeg", "ffmpeg.exe"), "-v", "error", "-y", "-i", str(audio_path),
                    "-t", "31", "-vn", "-ac", "1", "-ar", "24000", "-c:a", "pcm_s16le", str(target)],
                   check=True, capture_output=True, timeout=90, **subprocess_hidden_kwargs())
    with wave.open(str(target)) as reference:
        duration = reference.getnframes() / reference.getframerate()
        if not 0 < duration <= 30:
            raise ValueError("Use a short reference audio sample, up to 30 seconds.")


def save_cloned_voice(*, name, audio_path, ref_text, gender="any", description=""):
    if not name.strip() or not ref_text.strip() or not Path(audio_path).is_file():
        raise ValueError("Provide a voice name, reference audio and its transcript.")
    root = _voices_dir()
    root.mkdir(parents=True, exist_ok=True)
    voice_id = uuid4().hex
    audio = root/(voice_id+".wav")
    try:
        _convert_reference(audio_path, audio)
        meta = {"name": name.strip(), "ref_text": ref_text.strip(), "audio_file": audio.name,
                "gender": gender, "description": description.strip()}
        (root/(voice_id+".json")).write_text(json.dumps(meta, ensure_ascii=False, indent=2), encoding="utf-8")
    except BaseException:
        audio.unlink(missing_ok=True)
        raise
    return next(v for v in list_voices() if v["id"] == "omnivoice:"+voice_id)


def voice_fingerprint(voice):
    entry = next((v for v in list_voices() if v["id"] == voice), None)
    payload = {"runtime": RUNTIME_VERSION, "model": str(model_path()), "seed": 1234, "steps": inference_steps()}
    for path in (model_path(), Path(entry["ref_audio"]) if entry and entry.get("ref_audio") else None):
        if path and path.is_file():
            stat = path.stat()
            payload[str(path)] = (stat.st_size, stat.st_mtime_ns)
    if entry:
        payload["ref_text"] = entry.get("ref_text", "")
    return hashlib.sha256(json.dumps(payload, sort_keys=True).encode()).hexdigest()


class OmniVoiceRuntime:
    def __init__(self):
        self._generation = threading.Lock()
        self.process = None
        self._log = None
        self._directory = None
        self._key = None
        self.url = ""
        self.model_id = ""
        self.log_path = None
        self.http = requests.Session()
        self.http.trust_env = False  # local traffic must not go through proxies

    def close(self):
        # Never wait on the generation lock: app shutdown must interrupt a
        # pending request rather than block behind a long inference.
        process, self.process = self.process, None
        if process and process.poll() is None:
            process.terminate()
            try:
                process.wait(timeout=3)
            except subprocess.TimeoutExpired:
                process.kill()
                process.wait(timeout=3)
        if self._log:
            self._log.close()
            self._log = None
        if self._directory:
            try:
                self._directory.cleanup()
            except OSError:
                pass
            self._directory = None
        self._key = None

    def _ensure_server(self, progress):
        backend = selected_backend()
        binary, model = runtime_path(backend), model_path()
        cuda_dir = cuda_library_dir(binary.parent) if backend == "cuda" else None
        if not binary.is_file() or not model.is_file() or (backend == "cuda" and cuda_dir is None):
            raise RuntimeError("Download OmniVoice and the audio.cpp runtime in Manage Resources first.")
        key = (str(binary.resolve()), str(model.resolve()), backend, model.stat().st_mtime_ns, str(cuda_dir or ""))
        if self.process and self.process.poll() is None and self._key == key:
            return
        self.close()
        root = Path(temp_path("omnivoice"))
        root.mkdir(parents=True, exist_ok=True)
        self._directory = tempfile.TemporaryDirectory(prefix="session-", dir=root)
        folder = Path(self._directory.name)
        with socket.socket() as listener:
            listener.bind(("127.0.0.1", 0))
            port = listener.getsockname()[1]
        self.model_id = "capcap-omnivoice-"+uuid4().hex
        self.url = f"http://127.0.0.1:{port}"
        config = {"host": "127.0.0.1", "port": port, "backend": backend,
                  "threads": max(1, min(8, (os.cpu_count() or 2)-1)), "lazy_load": True,
                  "max_loaded_models": 1, "idle_unload_ms": 180000, "log_request_body": False,
                  "models": [{"id": self.model_id, "family": "omnivoice", "path": str(model.resolve()),
                              "task": "tts", "mode": "offline"}]}
        config_path = folder/"server.json"
        config_path.write_text(json.dumps(config), encoding="utf-8")
        logs = Path(join_root("logs"))
        logs.mkdir(parents=True, exist_ok=True)
        self.log_path = logs / (self.model_id + ".log")
        self._log = self.log_path.open("ab", buffering=0)
        env = dict(os.environ)
        paths = [str(binary.parent)] + ([str(cuda_dir)] if cuda_dir else [])
        env["PATH"] = os.pathsep.join(paths)+os.pathsep+env.get("PATH", "")
        try:
            self.process = subprocess.Popen([str(binary), "--config", str(config_path), "--no-ui"],
                cwd=str(binary.parent), env=env, stdout=self._log, stderr=subprocess.STDOUT, **subprocess_hidden_kwargs())
            if progress:
                progress(f"Starting OmniVoice (audio.cpp, {backend})...")
            deadline = time.monotonic()+30
            while time.monotonic() < deadline:
                if self.process is None or self.process.poll() is not None:
                    raise RuntimeError("audio.cpp could not start. Check the OmniVoice server log.")
                try:
                    response = self.http.get(self.url+"/v1/models", timeout=1)
                    response.raise_for_status()
                    if any(m.get("id") == self.model_id for m in response.json().get("data", [])):
                        self._key = key
                        print(f"[OmniVoice] audio.cpp {RUNTIME_VERSION}; backend={backend}; cuda_libraries={cuda_dir}; pid={self.process.pid}; log={self.log_path}")
                        return
                except (requests.RequestException, ValueError):
                    pass
                time.sleep(.1)
            raise RuntimeError("Timed out starting the OmniVoice audio.cpp runtime.")
        except Exception as exc:
            detail = self.log_path.read_text(encoding="utf-8", errors="replace")[-3000:] if self.log_path.is_file() else ""
            self.close()
            raise RuntimeError(f"OmniVoice runtime startup failed: {exc}. {detail}") from exc

    def synthesize(self, *, text, wav_path, voice, language=None, speed=1., on_progress=None):
        if not str(text).strip():
            raise ValueError("Speech text cannot be empty.")
        if not math.isfinite(float(speed)) or not .5 <= float(speed) <= 2.:
            raise ValueError("OmniVoice speed must be between 0.5 and 2.")
        entry = next((v for v in list_voices() if v["id"] == voice), None)
        if not entry or not entry.get("ref_audio") or not str(entry.get("ref_text") or "").strip():
            raise ValueError("Choose a cloned voice with reference audio and transcript for OmniVoice.")
        with self._generation:
            self._ensure_server(on_progress)
            options = {"num_inference_steps": inference_steps(), "guidance_scale": 2., "seed": 1234}
            if language:
                options["language"] = str(language)
            payload = {"model": self.model_id, "input": str(text).strip(), "response_format": "wav",
                       "speed": float(speed), "options": options}
            if entry.get("ref_audio"):
                payload["voice_ref"] = entry["ref_audio"]
                payload["reference_text"] = entry["ref_text"]
            if on_progress:
                on_progress("Generating speech with OmniVoice (audio.cpp)...")
            target = Path(wav_path)
            target.parent.mkdir(parents=True, exist_ok=True)
            with tempfile.TemporaryDirectory(prefix=".omnivoice-", dir=target.parent) as folder:
                raw, converted = Path(folder)/"raw.wav", Path(folder)/"speech.wav"
                try:
                    if entry.get("reference_source") == "vieneu":
                        # VieNeu references may be MP3/M4A or have a different
                        # sample rate. Convert a temporary copy, preserving originals.
                        reference = Path(folder)/"reference.wav"
                        _convert_reference(entry["ref_audio"], reference)
                        payload["voice_ref"] = str(reference.resolve())
                    with self.http.post(self.url+"/v1/audio/speech", json=payload, stream=True, timeout=(10, 600)) as response:
                        if not response.ok:
                            raise RuntimeError(f"OmniVoice failed ({response.status_code}): {response.text[:1500]}")
                        with raw.open("wb") as dst:
                            for chunk in response.iter_content(1024*1024):
                                if chunk:
                                    dst.write(chunk)
                    with raw.open("rb") as source:
                        if source.read(4) != b"RIFF":
                            raise RuntimeError("OmniVoice returned invalid audio.")
                    subprocess.run([bin_path("ffmpeg", "ffmpeg.exe"), "-v", "error", "-y", "-i", str(raw),
                        "-ac", "1", "-ar", "16000", "-c:a", "pcm_s16le", str(converted)],
                        check=True, capture_output=True, timeout=90, **subprocess_hidden_kwargs())
                    with wave.open(str(converted)) as result:
                        if result.getnframes() == 0:
                            raise RuntimeError("OmniVoice returned empty audio.")
                        while True:
                            samples = result.readframes(8192)
                            if not samples:
                                raise RuntimeError("OmniVoice returned silent audio.")
                            if any(samples):
                                break
                    os.replace(converted, target)
                except (requests.Timeout, requests.ConnectionError):
                    # A timed-out inference must not keep occupying the
                    # server while later cues queue behind it.
                    self.close()
                    raise
            return str(target)


_runtime = OmniVoiceRuntime()
atexit.register(_runtime.close)


def synthesize_omnivoice_wav_16k_mono(*, text, wav_path, voice, language=None, speed=1., on_progress=None, **_):
    return _runtime.synthesize(text=text, wav_path=wav_path, voice=voice, language=language, speed=speed, on_progress=on_progress)


def unload_omnivoice():
    _runtime.close()
