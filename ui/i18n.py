I18N_ROLE = 0x0100 + 1000


def _source_for_text(value: str) -> str | None:
    for source, translated in VI_TRANSLATIONS.items():
        if translated == value and source != value:
            return source
    return None


def _translate_object_value(obj, getter, setter, property_name: str) -> None:
    current = str(getter() or "")
    if not current:
        return
    stored = obj.property(property_name)
    known_values = {
        str(stored),
        _translate_text(str(stored), "en"),
        _translate_text(str(stored), "vi"),
    } if stored is not None else set()
    if stored is None or current not in known_values:
        stored = _source_for_text(current) or current
        obj.setProperty(property_name, stored)
    obj.setProperty(f"{property_name}_language", current_language())
    setter(_translate_text(str(stored), current_language()))


def localize_widget_tree(root) -> None:
    """Translate visible Qt copy while retaining the English source per object."""
    try:
        from PySide6.QtWidgets import QComboBox, QGroupBox, QLineEdit, QPlainTextEdit, QTabWidget, QTextEdit, QWidget
    except ImportError:
        return

    widgets = [root]
    if isinstance(root, QWidget):
        widgets.extend(root.findChildren(QWidget))
    for widget in widgets:
        if isinstance(widget, QComboBox):
            for index in range(widget.count()):
                current = widget.itemText(index)
                stored = widget.itemData(index, I18N_ROLE)
                known_values = {
                    str(stored),
                    _translate_text(str(stored), "en"),
                    _translate_text(str(stored), "vi"),
                } if stored is not None else set()
                if stored is None or current not in known_values:
                    stored = _source_for_text(current) or current
                    widget.setItemData(index, stored, I18N_ROLE)
                widget.setItemData(index, current_language(), I18N_ROLE + 1)
                widget.setItemText(index, _translate_text(str(stored), current_language()))
        elif isinstance(widget, QTabWidget):
            for index in range(widget.count()):
                _translate_object_value(
                    widget, lambda i=index: widget.tabText(i),
                    lambda value, i=index: widget.setTabText(i, value),
                    f"_capcap_i18n_tab_{index}",
                )
        elif isinstance(widget, (QLineEdit, QPlainTextEdit, QTextEdit)):
            # User-entered paths, API values, style instructions, and prompt
            # bodies are payload, not localizable UI copy.
            pass
        elif hasattr(widget, "text") and hasattr(widget, "setText"):
            _translate_object_value(widget, widget.text, widget.setText, "_capcap_i18n_text")
        if hasattr(widget, "windowTitle") and hasattr(widget, "setWindowTitle"):
            _translate_object_value(widget, widget.windowTitle, widget.setWindowTitle, "_capcap_i18n_title")
        if hasattr(widget, "toolTip") and hasattr(widget, "setToolTip"):
            _translate_object_value(widget, widget.toolTip, widget.setToolTip, "_capcap_i18n_tooltip")
        if hasattr(widget, "statusTip") and hasattr(widget, "setStatusTip"):
            _translate_object_value(widget, widget.statusTip, widget.setStatusTip, "_capcap_i18n_status")
        if hasattr(widget, "placeholderText") and hasattr(widget, "setPlaceholderText"):
            _translate_object_value(widget, widget.placeholderText, widget.setPlaceholderText, "_capcap_i18n_placeholder")
        if isinstance(widget, QGroupBox):
            _translate_object_value(widget, widget.title, widget.setTitle, "_capcap_i18n_group_title")
        for action in widget.actions() if hasattr(widget, "actions") else ():
            if hasattr(action, "text") and hasattr(action, "setText"):
                _translate_object_value(action, action.text, action.setText, "_capcap_i18n_action_text")
            if hasattr(action, "toolTip") and hasattr(action, "setToolTip"):
                _translate_object_value(action, action.toolTip, action.setToolTip, "_capcap_i18n_action_tooltip")


class _LanguageEventFilter:
    def __init__(self, app):
        from PySide6.QtCore import QObject

        class _Filter(QObject):
            def eventFilter(self, obj, event):
                from PySide6.QtCore import QEvent

                if event.type() in (QEvent.Show, QEvent.ShowToParent):
                    localize_widget_tree(obj)
                return False

        self.object = _Filter(app)
        app.installEventFilter(self.object)


def install_language_filter(app=None) -> None:
    try:
        from PySide6.QtWidgets import QApplication

        app = app or QApplication.instance()
        if app is not None and not getattr(app, "_capcap_language_filter", None):
            app._capcap_language_filter = _LanguageEventFilter(app)
    except ImportError:
        return


def normalize_language(value: Any) -> str:
    raw = str(value or "").strip().lower().replace("_", "-")
    if raw in {"vi", "vi-vn", "vietnamese", "tiếng việt", "tieng viet"}:
        return "vi"
    return DEFAULT_LANGUAGE


def _settings():
    from PySide6.QtCore import QSettings

    return QSettings("CapCap", "VideoTranslatorGUI")


def get_language(settings=None) -> str:
    store = settings if settings is not None else _settings()
    return normalize_language(store.value(SETTINGS_KEY, DEFAULT_LANGUAGE))


def set_language(value: Any, settings=None) -> str:
    global _current_language

    language = normalize_language(value)
    _current_language = language
    store = settings if settings is not None else _settings()
    store.setValue(SETTINGS_KEY, language)
    try:
        from PySide6.QtWidgets import QApplication

        app = QApplication.instance()
        if app is not None:
            install_language_filter(app)
            for window in app.topLevelWidgets():
                localize_widget_tree(window)
    except ImportError:
        pass
    return language


def current_language() -> str:
    global _current_language

    if _current_language is None:
        _current_language = get_language()
    return _current_language


def t(source_text: str, **values: Any) -> str:
    source = str(source_text)
    translated = _translate_text(source, current_language())
    return translated.format(**values) if values else translated


