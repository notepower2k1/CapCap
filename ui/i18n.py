def current_source_text(combo) -> str:
    """Return a combo's stable English source label after UI translation."""
    if combo is None:
        return ""
    try:
        value = combo.itemData(combo.currentIndex(), I18N_ROLE)
        return str(value if value is not None else combo.currentText())
    except (AttributeError, TypeError):
        return str(getattr(combo, "currentText", lambda: "")() or "")


def set_current_source_text(combo, value: Any) -> bool:
    """Select a combo item by its English source label in either locale."""
    if combo is None:
        return False
    target = str(value or "")
    index = combo.findData(target, I18N_ROLE)
    if index < 0:
        index = combo.findText(target)
    if index < 0:
        return False
    combo.setCurrentIndex(index)
    return True
